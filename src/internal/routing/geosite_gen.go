//go:build ignore

// Генератор geosite_data.go — снимка нужных категорий geosite из
// v2fly/domain-list-community (MIT). Запуск: go generate ./internal/routing
// (нужен интернет). Перед релизом снимок обновляется, а без сети остаётся
// прежний — сборка от него не зависит.
//
// Формат файлов data/<категория>: имя (= domain:), domain:, full:, keyword:,
// regexp:, include:<категория>; после правила — атрибуты @ads и т. п.,
// после # — комментарий. Берём domain и full, include раскрываем; keyword и
// regexp пропускаем (их и сам проект не советует, и в нужных нам
// категориях их нет — счётчик пишется в заголовок файла).
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"sort"
	"strings"
	"time"
)

// categories — категории, которые нужны группам (groups.go).
var categories = []string{"mailru-group", "yandex", "category-gov-ru", "category-bank-ru"}

const repo = "v2fly/domain-list-community"

var client = &http.Client{Timeout: 30 * time.Second}

func get(url string) ([]byte, error) {
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(io.LimitReader(resp.Body, 4<<20))
}

func main() {
	var head struct {
		SHA    string `json:"sha"`
		Commit struct {
			Committer struct {
				Date string `json:"date"`
			} `json:"committer"`
		} `json:"commit"`
	}
	b, err := get("https://api.github.com/repos/" + repo + "/commits/master")
	if err == nil {
		err = json.Unmarshal(b, &head)
	}
	if err != nil || head.SHA == "" {
		fmt.Fprintln(os.Stderr, "geosite: нет связи с GitHub, снимок не обновлён:", err)
		return // старый geosite_data.go остаётся
	}

	files := map[string][]string{}
	var load func(name string) ([]string, error)
	skipped := 0
	load = func(name string) ([]string, error) {
		if v, ok := files[name]; ok {
			return v, nil
		}
		files[name] = nil // от циклов include
		raw, err := get("https://raw.githubusercontent.com/" + repo + "/" + head.SHA + "/data/" + name)
		if err != nil {
			return nil, err
		}
		var out []string
		for _, line := range strings.Split(string(raw), "\n") {
			if i := strings.IndexByte(line, '#'); i >= 0 {
				line = line[:i]
			}
			f := strings.Fields(line)
			if len(f) == 0 {
				continue
			}
			rule := strings.ToLower(f[0]) // f[1:] — атрибуты, не нужны
			switch {
			case strings.HasPrefix(rule, "include:"):
				sub, err := load(strings.TrimPrefix(rule, "include:"))
				if err != nil {
					return nil, err
				}
				out = append(out, sub...)
			case strings.HasPrefix(rule, "full:"):
				out = append(out, rule)
			case strings.HasPrefix(rule, "domain:"):
				out = append(out, strings.TrimPrefix(rule, "domain:"))
			case strings.HasPrefix(rule, "keyword:"), strings.HasPrefix(rule, "regexp:"):
				skipped++
			default:
				out = append(out, rule)
			}
		}
		files[name] = out
		return out, nil
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, `// Code generated by geosite_gen.go; DO NOT EDIT.

// Снимок категорий geosite из https://github.com/%s
// (MIT License, Copyright (c) 2018-2019 V2Ray), коммит %s от %s.
// Пропущено правил keyword/regexp: %d.

package routing

// geositeCommit — с какого коммита снят снимок.
const geositeCommit = %q

// geosite — категория → правила: имя (с поддоменами) или "full:имя" (только
// оно само).
var geosite = map[string][]string{
`, repo, head.SHA[:12], head.Commit.Committer.Date, skipped, head.SHA[:12])
	for _, c := range categories {
		rules, err := load(c)
		if err != nil {
			fmt.Fprintln(os.Stderr, "geosite: снимок не обновлён:", err)
			return
		}
		rules = uniq(rules)
		fmt.Fprintf(&buf, "\t%q: {\n", c)
		for _, r := range rules {
			fmt.Fprintf(&buf, "\t\t%q,\n", r)
		}
		buf.WriteString("\t},\n")
	}
	buf.WriteString("}\n")
	src, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile("geosite_data.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func uniq(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, r := range in {
		if !seen[r] {
			seen[r] = true
			out = append(out, r)
		}
	}
	sort.Strings(out)
	return out
}
